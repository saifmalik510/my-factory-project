function checkId(id) {
  const url = `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=600&q=80`;
  return new Promise((resolve) => {
    const req = https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
      resolve({ id, status: res.statusCode, ok: res.statusCode === 200 || res.statusCode === 302 });
    });
    req.on('error', () => resolve({ id, ok: false }));
    req.setTimeout(4000, () => { req.destroy(); resolve({ id, ok: false }); });
  });
}

async function run() {
  const uniqueCandidates = [...new Set(CANDIDATE_IDS)];
  console.log(`Checking ${uniqueCandidates.length} candidate Unsplash IDs for HTTP 200 validity...`);
  
  const validIds = [];
  for (let i = 0; i < uniqueCandidates.length; i += 15) {
    const chunk = uniqueCandidates.slice(i, i + 15);
    const res = await Promise.all(chunk.map(checkId));
    res.forEach((r) => {
      if (r.ok) validIds.push(r.id);
    });
    process.stdout.write(`Progress: ${validIds.length} valid verified so far...\r`);
  }
  
  console.log(`\nFound ${validIds.length} 100% verified valid Unsplash photo IDs.`);
  fs.writeFileSync('scratch/verified_ids.json', JSON.stringify(validIds, null, 2));
}

